#!/usr/bin/env node
/* Flux Suite from public/data/products.json, the one list of Flux products.
   Writes:
   - public/data/products.js: window.FluxProducts, a plain script every page
     loads before flux-hub.js (which reads it for the switcher).
   - suite.html, between the FLUX_SUITE_STATIC markers: the directory as plain
     HTML, rendered by the same public/js/flux-suite-render.js the browser uses,
     so the page paints at once and works without JavaScript.
   --check exits non-zero, writing nothing, when either is out of date (CI). */
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const ROOT = new URL('..', import.meta.url);
const read = (p) => readFileSync(new URL(p, ROOT), 'utf8');
const check = process.argv.includes('--check');
const data = JSON.parse(read('public/data/products.json'));

const productsJs = '/* Generated by scripts/build-suite.mjs from public/data/products.json. Edit the JSON, not this file. */\n'
  + 'window.FluxProducts = ' + JSON.stringify({ groups: data.groups, products: data.products.map(({ note, ...p }) => p) }, null, 2) + ';\n';

/* Run the real browser files against a do-nothing DOM: flux-hub.js for its
   escape and product list, the renderer for the markup. */
const noop = () => {};
const el = () => ({ setAttribute: noop, appendChild: noop, style: {}, classList: { add: noop } });
const document = { readyState: 'complete', querySelectorAll: () => [], getElementById: () => null, addEventListener: noop, createElement: el, head: el(), body: null, currentScript: null };
const window = { addEventListener: noop, matchMedia: () => ({ matches: false }), navigator: {} };
const sandbox = { window, document, location: { href: 'https://fluxplanner.github.io/Flux/suite.html' }, navigator: {}, setTimeout: noop, URL, Image: function () {}, globalThis: null };
sandbox.globalThis = sandbox;
vm.createContext(sandbox);
for (const src of [productsJs, read('public/js/flux-hub.js'), read('public/js/flux-suite-render.js')]) vm.runInContext(src, sandbox);
const hub = window.FluxHub;
const R = window.FluxSuiteRender;
const list = hub.PRODUCTS.filter((p) => !p.ownerOnly);
const out = R.render({ list, groups: hub.GROUPS, esc: hub.esc });

const START = '<!-- FLUX_SUITE_STATIC:START -->';
const END = '<!-- FLUX_SUITE_STATIC:END -->';
const page = read('suite.html');
const a = page.indexOf(START);
const b = page.indexOf(END);
if (a < 0 || b < a) { console.error('suite.html has no FLUX_SUITE_STATIC markers'); process.exit(1); }
const block = START + '\n    <!-- Generated by scripts/build-suite.mjs from public/data/products.json. Edit the JSON, not this block. -->\n'
  + '    <div class="apps" id="apps" role="region" aria-labelledby="appsTitle" tabindex="-1" data-sig="' + R.signature(list) + '|">'
  + out.html + '</div>\n    ' + END;
const nextPage = page.slice(0, a) + block + page.slice(b + END.length);

const stale = [];
if (read('public/data/products.js') !== productsJs) stale.push('public/data/products.js');
if (nextPage !== page) stale.push('suite.html');
if (check) {
  if (stale.length) { console.error('Out of date: ' + stale.join(', ') + ' — run npm run build:suite'); process.exit(1); }
  console.log('✓ Suite markup and products.js match products.json');
} else {
  writeFileSync(new URL('public/data/products.js', ROOT), productsJs);
  writeFileSync(new URL('suite.html', ROOT), nextPage);
  console.log('Wrote public/data/products.js and suite.html (' + list.length + ' products)');
}
